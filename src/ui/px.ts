export type PixelIcon = keyof typeof PX;

const rects = (rows: readonly string[], dy = 0): string => {
  let s = '';
  rows.forEach((r, y) =>
    [...r].forEach((c, x) => c === '#' && (s += `<rect x="${x}" y="${y + dy}" width="1" height="1"/>`)),
  );
  return s;
};

/** An icon as SVG markup, in `fill` (the text colour by default). */
export function pxSVG(name: PixelIcon, fill = 'currentColor'): string {
  const viewBox = name === 'open' || name === 'save' ? '-0.5 -0.5 10 10' : '0 0 9 9';
  return `<svg viewBox="${viewBox}" fill="${fill}" shape-rendering="crispEdges" aria-hidden="true">${rects(PX[name])}</svg>`;
}

/** A `<span class="ic">` holding an icon. */
export function icon(name: PixelIcon, small = false): HTMLSpanElement {
  const span = document.createElement('span');
  span.className = small ? 'ic sm' : 'ic';
  span.innerHTML = pxSVG(name);
  return span;
}

/** Fills every `.ic[data-ic]` placeholder under `scope` with its icon. */
export function paintIcons(scope: ParentNode = document): void {
  scope.querySelectorAll<HTMLElement>('.ic[data-ic]').forEach((el) => {
    const name = el.dataset.ic as PixelIcon;
    if (PX[name]) el.innerHTML = pxSVG(name);
  });
  scope.querySelectorAll<HTMLElement>('.cb > i:empty').forEach((i) => (i.innerHTML = pxSVG('check', '#fff')));
}

/** A colour darkened (k < 1) or lightened. */
export function shade(hex: string, k: number): string {
  const n = parseInt(hex.slice(1), 16);
  const f = (v: number): number => Math.max(0, Math.min(255, Math.round(v * k)));
  return `rgb(${f(n >> 16)},${f((n >> 8) & 255)},${f(n & 255)})`;
}

/** The wire colour button's icon: a square of the current colour, drawn in pixels like the other icons. */
export function wireIcon(color: string): string {
  const R = [
    '.........',
    '.ooooooo.',
    '.o#####o.',
    '.o#####o.',
    '.o#####o.',
    '.o#####o.',
    '.o#####o.',
    '.ooooooo.',
    '.........',
  ];
  const col: Record<string, string> = { o: shade(color, 0.72), '#': color };
  let s = '';
  R.forEach((r, y) =>
    [...r].forEach((ch, x) => {
      if (col[ch]) s += `<rect x="${x}" y="${y}" width="1" height="1" fill="${col[ch]}"/>`;
    }),
  );
  return `<svg viewBox="0 0 9 9" shape-rendering="crispEdges" aria-hidden="true">${s}</svg>`;
}

