/** The logo's art, 45 × 11: the rails on rows 0 and 10, the letters on rows 3 to 7. */
export function logoSVG(svg: SVGSVGElement): void {
  svg.setAttribute('viewBox', '0 0 45 11');
  svg.setAttribute('shape-rendering', 'crispEdges');
  svg.setAttribute('fill', INK);
  svg.innerHTML =
    `<rect x="0" y="0" width="45" height="1" fill="${RED}"/><rect x="0" y="10" width="45" height="1" fill="${BLUE}"/>` +
    rects(SILK, 3);
}

/**
 * Pixel art jaggies at browser zooms like 110 % because an art pixel lands on 2.5 screen pixels. --u is
 * an art pixel at about 2× and --u1 at about 1×, both rounded to whole device pixels; every pixel-art
 * size is a multiple of one of them. Runs again whenever the zoom changes.
 */
export function snapPixels(): void {
  const d = window.devicePixelRatio || 1;
  const root = document.documentElement.style;
  root.setProperty('--u', `${Math.max(1, Math.round(2 * d)) / d}px`);
  root.setProperty('--u1', `${Math.max(1, Math.round(d)) / d}px`);
  matchMedia(`(resolution: ${d}dppx)`).addEventListener('change', snapPixels, { once: true });
}
